// Generates, from registry.ts, the Rust table of curated EVM chains and tokens
// (apps/desktop/src-tauri/src/known_tokens/data.rs) and the JSON fixture the Rust tests compare
// it with (apps/desktop/src-tauri/fixtures/known_tokens.json). Fails when either file is stale;
// to regenerate after editing the registry:
//   pnpm --filter @kyro/chains exec vitest run -u test/known-tokens-table.test.ts

import { describe, expect, it } from 'vitest';
import { ERC20_TOKENS, SPL_TOKENS, TON_JETTONS, TRC20_TOKENS, evmChains } from '../src';

const NETWORKS = ['mainnet', 'testnet'] as const;
type Net = (typeof NETWORKS)[number];

interface FixtureChain {
  network: Net;
  chainId: number;
  name: string;
  nativeSymbol: string;
  /** Default RPC host: the shell checks it against EVM_DEFAULTS and the net_fetch allowlist. */
  rpcHost: string;
}
interface FixtureToken {
  network: Net;
  /** `evm:<chainId>`, `solana`, `tron` or `ton`. */
  chain: string;
  contract: string;
  symbol: string;
  name: string;
  decimals: number;
}
type Fixture = { evmChains: FixtureChain[]; tokens: FixtureToken[] };

export function knownTokensFixture(): Fixture {
  const chains: FixtureChain[] = [];
  const tokens: FixtureToken[] = [];
  const tok = (network: Net, chain: string, t: { contract: string; symbol: string; name: string; decimals: number }) =>
    tokens.push({ network, chain, contract: t.contract, symbol: t.symbol, name: t.name, decimals: t.decimals });
  for (const network of NETWORKS) {
    for (const c of evmChains(network)) {
      chains.push({ network, chainId: c.chainId, name: c.name, nativeSymbol: c.nativeSymbol, rpcHost: new URL(c.rpcUrl).host });
      for (const t of ERC20_TOKENS[c.key] ?? []) tok(network, `evm:${c.chainId}`, t);
    }
  }
  for (const network of NETWORKS) {
    for (const t of SPL_TOKENS[network]) tok(network, 'solana', t);
    for (const t of TRC20_TOKENS[network]) tok(network, 'tron', t);
    for (const t of TON_JETTONS[network]) tok(network, 'ton', t);
  }
  return { evmChains: chains, tokens };
}

/** Rust string literal: UTF-8 is kept as is, only `\` and `"` need escaping. */
const lit = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const net = (n: Net) => (n === 'mainnet' ? 'M' : 'N');
const chain = (c: string) => (c === 'solana' ? 'Solana' : c === 'tron' ? 'Tron' : c === 'ton' ? 'Ton' : `Evm(${c.slice('evm:'.length)})`);

export function renderRust(f: Fixture): string {
  return [
    '// @generated by packages/chains/test/known-tokens-table.test.ts from packages/chains/src/registry.ts.',
    '// Do not edit: pnpm --filter @kyro/chains exec vitest run -u test/known-tokens-table.test.ts',
    '',
    'use super::TokenChain::{Evm, Solana, Ton, Tron};',
    'use super::{Entry as E, KnownEvmChain as C, KnownToken as K};',
    'use wallet_core::Network::{Mainnet as M, Testnet as N};',
    '',
    'pub(super) const EVM_CHAINS: &[C] = &[',
    ...f.evmChains.map((c) => `    C { network: ${net(c.network)}, chain_id: ${c.chainId}, name: ${lit(c.name)}, native_symbol: ${lit(c.nativeSymbol)} },`),
    '];',
    '',
    'pub(super) const TOKENS: &[E] = &[',
    ...f.tokens.map(
      (t) => `    E { network: ${net(t.network)}, chain: ${chain(t.chain)}, contract: ${lit(t.contract)}, token: K { symbol: ${lit(t.symbol)}, name: ${lit(t.name)}, decimals: ${t.decimals} } },`,
    ),
    '];',
    '',
  ].join('\n');
}

describe('table Rust des tokens connus (générée depuis registry.ts)', () => {
  it('fixture JSON à jour', async () => {
    await expect(JSON.stringify(knownTokensFixture(), null, 2) + '\n').toMatchFileSnapshot('../../../apps/desktop/src-tauri/fixtures/known_tokens.json');
  });
  it('table Rust à jour', async () => {
    await expect(renderRust(knownTokensFixture())).toMatchFileSnapshot('../../../apps/desktop/src-tauri/src/known_tokens/data.rs');
  });
});
