const htmlFiles = written.filter((f) => f.endsWith('.html'));
const idsCache = new Map();
function idsOf(file) {
  if (!idsCache.has(file)) idsCache.set(file, new Set([...readFileSync(join(OUT, file), 'utf8').matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])));
  return idsCache.get(file);
}
function target(url) {
  const [pathAndQuery, frag] = url.split('#');
  const path = pathAndQuery.split('?')[0];
  let file = path.endsWith('/') ? path.slice(1) + 'index.html' : path.slice(1);
  if (!existsSync(join(OUT, file)) && existsSync(join(OUT, file, 'index.html'))) file = join(file, 'index.html');
  return { file, frag, path };
}

let linkCount = 0;
for (const f of htmlFiles) {
  const src = readFileSync(join(OUT, f), 'utf8');
  const h1 = (src.match(/<h1[\s>]/g) || []).length;
  if (h1 !== 1) errors.push(`${f}: ${h1} <h1> elements (want 1)`);
  if (/\sstyle="/.test(src)) errors.push(`${f}: inline style attribute (blocked by CSP)`);
  for (const m of src.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>/g)) if (!/type="application\/ld\+json"/.test(m[1])) errors.push(`${f}: inline <script> (blocked by CSP)`);
  for (const m of src.matchAll(/\son[a-z]+="/g)) errors.push(`${f}: inline event handler ${m[0]}`);
  for (const m of src.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try {
      JSON.parse(m[1]);
    } catch (e) {
      errors.push(`${f}: invalid JSON-LD (${e.message})`);
    }
  }
  for (const m of src.matchAll(/<img\b[^>]*>/g)) if (!/\salt="/.test(m[0])) errors.push(`${f}: <img> without alt`);
  const refs = [...src.matchAll(/\s(?:href|src)="([^"]+)"/g), ...src.matchAll(/\ssrcset="([^"\s]+)/g)].map((m) => m[1]);
  for (const ref of refs) {
    if (/^(https?:|mailto:)/.test(ref)) {
      if (/^https?:\/\/(?!kyrowallet\.com|github\.com|trezor\.io)/.test(ref)) errors.push(`${f}: link to an unexpected host: ${ref}`);
      continue;
    }
    linkCount++;
    if (ref.startsWith('#')) {
      if (ref.length > 1 && !idsOf(f).has(ref.slice(1))) errors.push(`${f}: missing anchor ${ref}`);
      continue;
    }
    if (!ref.startsWith('/')) {
      errors.push(`${f}: relative link ${ref}`);
      continue;
    }
    const t = target(ref);
    if (!existsSync(join(OUT, t.file))) errors.push(`${f}: broken link ${ref}`);
    else if (t.frag && t.file.endsWith('.html') && !idsOf(t.file).has(t.frag)) errors.push(`${f}: missing anchor ${ref}`);
  }
}
for (const css of ['style.css', 'chains.css']) {
  for (const m of readFileSync(join(OUT, css), 'utf8').matchAll(/url\('?(\/[^')]+)'?\)/g)) if (!existsSync(join(OUT, m[1].slice(1)))) errors.push(`${css}: missing ${m[1]}`);
}
