for (const m of readFileSync(join(OUT, 'llms.txt'), 'utf8').matchAll(/\]\(https:\/\/kyrowallet\.com([^)]*)\)/g)) if (!existsSync(join(OUT, target(m[1]).file))) errors.push(`llms.txt: ${m[1]} does not exist`);

