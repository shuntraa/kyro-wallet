  if (!/^[a-z0-9-]+$/.test(c.slug || '')) errors.push(`chains.json: bad slug "${c.slug}"`);
  if (seen.has(c.slug)) errors.push(`chains.json: duplicate slug "${c.slug}"`);
  seen.add(c.slug);
  if (!['live', 'hidden'].includes(c.status)) errors.push(`chains.json: ${c.slug}: status must be "live" or "hidden"`);
  if (!/^#[0-9a-fA-F]{3,8}$/.test(c.color || '')) errors.push(`chains.json: ${c.slug}: color must be a hex colour`);
  for (const k of ['send', 'swap', 'staking', 'hardware']) if (typeof c.features?.[k] !== 'boolean') errors.push(`chains.json: ${c.slug}: features.${k} must be true or false`);
