// Plain text of each page's <main>, from the HTML we just wrote, so it never drifts from the site.
function htmlToText(src) {
  const main = src.slice(src.indexOf('<main'), src.indexOf('</main>'));
  const VOID = new Set(['img', 'br', 'source', 'meta', 'input', 'hr', 'link', 'wbr']);
  const SKIP = new Set(['script', 'style', 'svg', 'picture', 'button', 'nav']);
  const BLOCK = new Set(['p', 'div', 'section', 'li', 'tr', 'h1', 'h2', 'h3', 'h4', 'ul', 'ol', 'table', 'details', 'summary', 'figure', 'pre', 'header', 'article', 'caption']);
  let out = '';
  let skip = 0;
  const stack = [];
  const re = /<(\/?)([a-zA-Z0-9]+)([^>]*)>|([^<]+)/g;
  let m;
  while ((m = re.exec(main))) {
    if (m[4] !== undefined) {
      if (!skip) out += stack.includes('pre') ? m[4] : m[4].replace(/\s+/g, ' ');
      continue;
    }
    const [, close, tagRaw, attrs] = m;
    const tag = tagRaw.toLowerCase();
    if (VOID.has(tag)) continue;
    if (!close) {
      const hidden = /aria-hidden="true"/.test(attrs) || /class="[^"]*visually-hidden/.test(attrs);
      stack.push(tag);
      if (skip || SKIP.has(tag) || (hidden && tag !== 'caption')) skip++;
      if (skip) continue;
      if (/^h[1-4]$/.test(tag)) out += '\n\n' + '#'.repeat(Number(tag[1])) + ' ';
      else if (tag === 'li') out += '\n- ';
      else if (tag === 'summary') out += '\n\nQ: ';
      else if (tag === 'pre') out += '\n\n```\n';
      else if (tag === 'th' || tag === 'td') out += ' | ';
      else if (BLOCK.has(tag)) out += '\n\n';
    } else {
      const open = stack.pop();
      if (skip) {
        skip--;
        continue;
      }
      if (open === 'pre') out += '\n```\n';
      else if (open === 'summary') out += '\nA:';
      else if (open === 'strong') out += ': ';
      else if (BLOCK.has(open)) out += '\n';
    }
  }
  return out
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n[ \t]+(?=[^\s`])/g, '\n')
    .replace(/\n-\s*\n+(#+ )/g, '\n\n$1')
    .replace(/\n- \s*\n/g, '\n- ')
    .replace(/A:\s*\n+/g, 'A: ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const full = pages
  .map((p) => {
    const src = readFileSync(join(OUT, fileFor(p.path)), 'utf8');
    return `================================================================\n${p.title}\nURL: ${SITE}${p.path}\n================================================================\n\n${htmlToText(src)}\n`;
  })
  .join('\n');
write('llms-full.txt', ascii(`# Kyro Wallet: full text of kyrowallet.com\n\nGenerated ${today} from the published pages. Short index: ${SITE}/llms.txt\n\n${full}`));

// ------------------------------------------------------------------ checks

const htmlFiles = written.filter((f) => f.endsWith('.html'));
const idsCache = new Map();
function idsOf(file) {
  if (!idsCache.has(file)) idsCache.set(file, new Set([...readFileSync(join(OUT, file), 'utf8').matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])));
  return idsCache.get(file);
}
function target(url) {
  const [pathAndQuery, frag] = url.split('#');
  const path = pathAndQuery.split('?')[0];
  let file = path.endsWith('/') ? path.slice(1) + 'index.html' : path.slice(1);
  if (!existsSync(join(OUT, file)) && existsSync(join(OUT, file, 'index.html'))) file = join(file, 'index.html');
  return { file, frag, path };
}

let linkCount = 0;
for (const f of htmlFiles) {
  const src = readFileSync(join(OUT, f), 'utf8');
  const h1 = (src.match(/<h1[\s>]/g) || []).length;
  if (h1 !== 1) errors.push(`${f}: ${h1} <h1> elements (want 1)`);
  if (/\sstyle="/.test(src)) errors.push(`${f}: inline style attribute (blocked by CSP)`);
  for (const m of src.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>/g)) if (!/type="application\/ld\+json"/.test(m[1])) errors.push(`${f}: inline <script> (blocked by CSP)`);
  for (const m of src.matchAll(/\son[a-z]+="/g)) errors.push(`${f}: inline event handler ${m[0]}`);
  for (const m of src.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try {
      JSON.parse(m[1]);
    } catch (e) {
      errors.push(`${f}: invalid JSON-LD (${e.message})`);
    }
  }
  for (const m of src.matchAll(/<img\b[^>]*>/g)) if (!/\salt="/.test(m[0])) errors.push(`${f}: <img> without alt`);
  const refs = [...src.matchAll(/\s(?:href|src)="([^"]+)"/g), ...src.matchAll(/\ssrcset="([^"\s]+)/g)].map((m) => m[1]);
  for (const ref of refs) {
    if (/^(https?:|mailto:)/.test(ref)) {
      if (/^https?:\/\/(?!kyrowallet\.com|github\.com|trezor\.io)/.test(ref)) errors.push(`${f}: link to an unexpected host: ${ref}`);
      continue;
    }
    linkCount++;
    if (ref.startsWith('#')) {
      if (ref.length > 1 && !idsOf(f).has(ref.slice(1))) errors.push(`${f}: missing anchor ${ref}`);
      continue;
    }
    if (!ref.startsWith('/')) {
      errors.push(`${f}: relative link ${ref}`);
      continue;
    }
    const t = target(ref);
    if (!existsSync(join(OUT, t.file))) errors.push(`${f}: broken link ${ref}`);
    else if (t.frag && t.file.endsWith('.html') && !idsOf(t.file).has(t.frag)) errors.push(`${f}: missing anchor ${ref}`);
  }
}
// CSS url() references
for (const css of ['style.css', 'chains.css']) {
  for (const m of readFileSync(join(OUT, css), 'utf8').matchAll(/url\('?(\/[^')]+)'?\)/g)) if (!existsSync(join(OUT, m[1].slice(1)))) errors.push(`${css}: missing ${m[1]}`);
}
// Sitemap and llms.txt URLs must exist.
for (const m of readFileSync(join(OUT, 'sitemap.xml'), 'utf8').matchAll(/<loc>https:\/\/kyrowallet\.com([^<]*)<\/loc>/g)) if (!existsSync(join(OUT, target(m[1]).file))) errors.push(`sitemap.xml: ${m[1]} does not exist`);
for (const m of readFileSync(join(OUT, 'llms.txt'), 'utf8').matchAll(/\]\(https:\/\/kyrowallet\.com([^)]*)\)/g)) if (!existsSync(join(OUT, target(m[1]).file))) errors.push(`llms.txt: ${m[1]} does not exist`);

// public/ is served as is: the site's README lives in website/README.md, never in public/.
for (const f of readdirSync(OUT)) if (/^readme(\.|$)/i.test(f)) errors.push(`public/${f}: documentation must not be published (keep it in website/README.md)`);

if (errors.length) fail(errors);
console.log(`built ${pages.length} pages + 404 (${chains.length} live blockchains, ${all.length - chains.length} hidden); ${linkCount} internal links checked, all OK; ${iconCount} coin icons copied`);

function fail(list) {
  console.error(list.map((e) => '  ✗ ' + e).join('\n'));
  console.error(`${list.length} problem(s)`);
  process.exit(1);
}
