// Plain text of each page's <main>, from the HTML we just wrote, so it never drifts from the site.
function htmlToText(src) {
  const main = src.slice(src.indexOf('<main'), src.indexOf('</main>'));
  const VOID = new Set(['img', 'br', 'source', 'meta', 'input', 'hr', 'link', 'wbr']);
  const SKIP = new Set(['script', 'style', 'svg', 'picture', 'button', 'nav']);
  const BLOCK = new Set(['p', 'div', 'section', 'li', 'tr', 'h1', 'h2', 'h3', 'h4', 'ul', 'ol', 'table', 'details', 'summary', 'figure', 'pre', 'header', 'article', 'caption']);
  let out = '';
  let skip = 0;
  const stack = [];
  const re = /<(\/?)([a-zA-Z0-9]+)([^>]*)>|([^<]+)/g;
  let m;
  while ((m = re.exec(main))) {
    if (m[4] !== undefined) {
      if (!skip) out += stack.includes('pre') ? m[4] : m[4].replace(/\s+/g, ' ');
      continue;
    }
    const [, close, tagRaw, attrs] = m;
    const tag = tagRaw.toLowerCase();
    if (VOID.has(tag)) continue;
    if (!close) {
      const hidden = /aria-hidden="true"/.test(attrs) || /class="[^"]*visually-hidden/.test(attrs);
      stack.push(tag);
      if (skip || SKIP.has(tag) || (hidden && tag !== 'caption')) skip++;
      if (skip) continue;
      if (/^h[1-4]$/.test(tag)) out += '\n\n' + '#'.repeat(Number(tag[1])) + ' ';
      else if (tag === 'li') out += '\n- ';
      else if (tag === 'summary') out += '\n\nQ: ';
      else if (tag === 'pre') out += '\n\n```\n';
      else if (tag === 'th' || tag === 'td') out += ' | ';
      else if (BLOCK.has(tag)) out += '\n\n';
    } else {
      const open = stack.pop();
      if (skip) {
        skip--;
        continue;
      }
      if (open === 'pre') out += '\n```\n';
      else if (open === 'summary') out += '\nA:';
      else if (open === 'strong') out += ': ';
      else if (BLOCK.has(open)) out += '\n';
    }
  }
  return out
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n[ \t]+(?=[^\s`])/g, '\n')
    .replace(/\n-\s*\n+(#+ )/g, '\n\n$1')
    .replace(/\n- \s*\n/g, '\n- ')
    .replace(/A:\s*\n+/g, 'A: ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

